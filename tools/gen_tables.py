#!/usr/bin/env python3
"""Generate the Rust data tables from the neutral tables in tools/defs/.

    tools/defs/input_methods.tsv -> crates/vnkey-core/src/im_defs.rs
    tools/defs/charset.tsv       -> crates/vnkey-core/src/charset.rs

The TSV files are the source of truth; this script only formats them into Rust
and checks that they are consistent. Nothing here reads any other language.

    python3 tools/gen_tables.py            # rewrite the two .rs files
    python3 tools/gen_tables.py --check    # exit 1 if they have drifted

TSV format: `#` starts a comment, rows are TAB separated, and the three escape
sequences \\ \\t \\n plus \\uXXXX keep tabs, newlines and invisible codepoints
(the TCVN3 table maps u+01b0 to a soft hyphen) visible and unambiguous.
Rows are order-preserving; grouping is by consecutive equal first column.
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFS = ROOT / "tools" / "defs"
OUT = ROOT / "crates" / "vnkey-core" / "src"


def tsv_unescape(text: str) -> str:
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        nxt = text[i + 1]
        if nxt == "\\":
            out.append("\\")
            i += 2
        elif nxt == "t":
            out.append("\t")
            i += 2
        elif nxt == "n":
            out.append("\n")
            i += 2
        elif nxt == "u":
            out.append(chr(int(text[i + 2:i + 6], 16)))
            i += 6
        else:
            raise ValueError(f"unknown escape \\{nxt} in {text!r}")
    return "".join(out)


def is_invisible(ch: str) -> bool:
    """Codepoints clippy rejects inside string literals (soft hyphen, bidi marks)."""
    cp = ord(ch)
    return cp == 0xAD or cp == 0xFEFF or 0x200B <= cp <= 0x200F or 0x2060 <= cp <= 0x2064


def rust_char(ch: str) -> str:
    if ch == "'":
        return "'\\''"
    if ch == "\\":
        return "'\\\\'"
    if ch == "\n":
        return "'\\n'"
    if ch == "\t":
        return "'\\t'"
    if ch == " ":
        return "' '"
    if ord(ch) < 0x20 or ord(ch) == 0x7F or is_invisible(ch):
        return f"'\\u{{{ord(ch):x}}}'"
    return f"'{ch}'"


def rust_str(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F or is_invisible(ch):
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def read_tsv(path: pathlib.Path) -> list[tuple[str, str, str]]:
    rows = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3:
            raise SystemExit(f"{path.name}:{lineno}: expected 3 fields, got {len(fields)}")
        rows.append(tuple(tsv_unescape(f) for f in fields))
    if not rows:
        raise SystemExit(f"{path.name}: no data rows")
    return rows


def group(rows: list[tuple[str, str, str]], what: str) -> list[tuple[str, list[tuple[str, str]]]]:
    """Collapse order-preserving rows into (group, [(key, value)]) blocks.

    A row with an empty key declares an empty group: two charsets are computed
    at encode time and have no table of their own, but they still have to exist
    in the generated list, so they need a row that carries only the name.
    """
    groups: list[tuple[str, list[tuple[str, str]]]] = []
    for outer, key, value in rows:
        if not groups or groups[-1][0] != outer:
            if any(name == outer for name, _ in groups):
                raise SystemExit(f"{what}: rows for {outer!r} are not contiguous")
            groups.append((outer, []))
        if key == "":
            if value != "":
                raise SystemExit(f"{what}: group marker for {outer!r} has a value")
            continue
        pairs = groups[-1][1]
        if any(k == key for k, _ in pairs):
            raise SystemExit(f"{what}: duplicate key {key!r} in {outer!r}")
        pairs.append((key, value))
    return groups


def render_input_methods() -> tuple[str, str]:
    groups = group(read_tsv(DEFS / "input_methods.tsv"), "input_methods.tsv")
    lines = [
        "// @generated by tools/gen_tables.py from tools/defs/input_methods.tsv. Do not edit.",
        "",
        "/// Input method definitions: name -> (key, DSL rule) pairs, source order.",
        "pub static INPUT_METHOD_DEFINITIONS: &[(&str, &[(&str, &str)])] = &[",
    ]
    for name, pairs in groups:
        lines.append(f"    ({rust_str(name)}, &[")
        for key, rule in pairs:
            lines.append(f"        ({rust_str(key)}, {rust_str(rule)}),")
        lines.append("    ]),")
    lines.append("];")
    return "\n".join(lines) + "\n", f"{len(groups)} input methods, {sum(len(p) for _, p in groups)} rules"


def render_charsets() -> tuple[str, str]:
    groups = group(read_tsv(DEFS / "charset.tsv"), "charset.tsv")
    lines = [
        "// @generated by tools/gen_tables.py from tools/defs/charset.tsv. Do not edit.",
        "",
        "/// Legacy output charsets: name -> (input char, output string).",
        "pub static CHARSETS: &[(&str, &[(char, &str)])] = &[",
    ]
    for name, entries in groups:
        lines.append(f"    ({rust_str(name)}, &[")
        for src, dst in entries:
            if len(src) != 1:
                raise SystemExit(f"charset.tsv: key {src!r} in {name!r} is not one char")
            lines.append(f"        ({rust_char(src)}, {rust_str(dst)}),")
        lines.append("    ]),")
    lines.append("];")
    return "\n".join(lines) + "\n", f"{len(groups)} charsets, {sum(len(e) for _, e in groups)} entries"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="do not write; fail if the .rs files differ from the tables")
    args = parser.parse_args()

    im_defs, im_stats = render_input_methods()
    charset, charset_stats = render_charsets()
    outputs = {OUT / "im_defs.rs": im_defs, OUT / "charset.rs": charset}
    stats = {OUT / "im_defs.rs": im_stats, OUT / "charset.rs": charset_stats}

    if args.check:
        drifted = [p.name for p, text in outputs.items()
                   if not p.exists() or p.read_text(encoding="utf-8") != text]
        if drifted:
            print(f"out of date: {', '.join(drifted)} (run tools/gen_tables.py)")
            return 1
        print(f"tables and generated files agree ({', '.join(sorted(p.name for p in outputs))})")
        return 0

    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"{path.name}: {stats[path]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
